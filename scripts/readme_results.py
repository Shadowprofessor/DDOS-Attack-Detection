# -*- coding: utf-8 -*-
"""Build the "Results" block shown in README.md and REPORT.md from the results files (v6.1.0).

    python scripts/readme_results.py          # rewrite the block in README.md and REPORT.md
    python scripts/readme_results.py --check  # exit 1 if either file has drifted (CI: tests/test_readme_results.py)

Nothing is typed by hand. Sources:
  docs/eval/live/live*.json           live MTTD on the website + MTTC from OVS counters
  docs/eval/live/annotations.json     the few written-down judgement calls (exclusions, lost runs)
  docs/purple_team/{dev,heldout}/results.json   offline lab coverage, DEV vs HELD-OUT (never merged)
  docs/eval/triage/results.json       agent triage accuracy (rules vs Lightning vs ML)
"""
from __future__ import annotations

import argparse
import json
import re
import statistics
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
START, END = "<!-- RESULTS:START (generated by scripts/readme_results.py; do not edit by hand) -->", "<!-- RESULTS:END -->"
TARGETS = (REPO / "README.md", REPO / "REPORT.md")


def _load(rel: str):
    return json.loads((REPO / rel).read_text(encoding="utf-8"))


def _num(run: str) -> int:
    return int(re.sub(r"\D", "", run) or 0)


def _short(s: str) -> str:
    return s.replace("contain_", "").replace("_", " ")


def live_rows(ann: dict):
    runs = sorted((p for p in (REPO / "docs/eval/live").glob("live*.json")), key=lambda p: _num(p.stem))
    mttd, mttc, udp_names = [], [], []
    for p in runs:
        d = json.loads(p.read_text(encoding="utf-8"))
        run = d.get("run") or p.stem
        for r in d.get("results", []):
            key = f"{run}/{r['scenario']}"
            excluded = ann["exclude_mttd"].get(key)
            mttd.append({"run": run, "scenario": r["scenario"], "s": r.get("website_s"), "excluded": excluded,
                         "verdict": r.get("l3_verdict") or "", "source": r.get("l3_source") or ""})
            if "udp" in r["scenario"] and r.get("l3_source", "").startswith("llm:"):
                udp_names.append((run, "udp" in (r.get("l3_verdict") or "").lower()))
        for i, c in enumerate(d.get("containment") or []):
            if f"{run}/containment/{i}" in ann["exclude_mttc"]:
                continue
            mttc.append({"run": run, **c})
    return mttd, mttc, udp_names


def _trim(text: str, n: int = 60) -> str:
    text = " ".join(str(text).split())
    if len(text) <= n:
        return text
    return text[:n].rsplit(" ", 1)[0] + "…"


def coverage_rows():
    dev = {r["scenario"]: r for r in _load("docs/purple_team/dev/results.json")["results"]}
    held = {r["scenario"]: r for r in _load("docs/purple_team/heldout/results.json")["results"]}
    return dev, held


def _cell(r: dict) -> str:
    if r is None:
        return "—"
    o = r["outcome"]
    if not r["expected_incident"]:
        return "no alarm ✓" if o == "clean" else f"**false alarm** ({o})"
    m = r.get("mttd_s")
    t = "" if m is None else (f", {m:.1f} s" if m >= 0 else ", < 0 s†")
    return f"{o}{t}"


def build() -> tuple[str, dict]:
    ann = _load("docs/eval/live/annotations.json")
    mttd, mttc, udp_names = live_rows(ann)
    dev, held = coverage_rows()
    tri = _load("docs/eval/triage/results.json")["sets"]
    tdev, thel = tri["DEV (runs 2+3)"], tri["HELD-OUT (run4)"]

    valid = [m["s"] for m in mttd if m["s"] is not None and not m["excluded"]]
    med = statistics.median(valid)
    good = [c for c in mttc if c.get("mttc_s") is not None]
    h = {
        "live_mttd": f"{min(valid):.2f}–{max(valid):.2f} s, median {med:.2f} s ({len(valid)} floods)",
        "mttc": " and ".join(f"{c['mttc_s']:.2f} s ({c['run']})" for c in good) or "not reached",
        "heldout_detected": f"{sum(1 for r in held.values() if r['expected_incident'] and r['outcome'] == 'detected')}/"
                            f"{sum(1 for r in held.values() if r['expected_incident'])}",
        "heldout_false_alarms": f"{sum(1 for r in held.values() if not r['expected_incident'] and r['outcome'] != 'clean')}/"
                                f"{sum(1 for r in held.values() if not r['expected_incident'])}",
        "udp_misnamed": f"{sum(1 for _, ok in udp_names if not ok)} of {len(udp_names)}",
    }

    def frac(m: dict, k: str) -> str:
        return f"{round(m[k] * m['n_attacks'])}/{m['n_attacks']}"

    L = [START, "", "#### Live demo (Mininet on WSL2 → SOC website, real time)", "",
         "| Run | Scenario | Attack start → alert on website | L3 (Lightning) named it |", "|---|---|---:|---|"]
    notes = []
    for m in mttd:
        s = "—" if m["s"] is None else f"{m['s']:.2f} s"
        if m["excluded"]:
            notes.append(f"{m['run']} {_short(m['scenario'])}: {m['excluded']}.")
            s = f"excluded ({len(notes)})"
        L.append(f"| {m['run']} | {_short(m['scenario'])} | {s} | {_trim(m['verdict'])} |")
    for run, why in ann["lost_runs"].items():
        notes.append(f"{run}: {why}.")
        L.append(f"| {run} | — | lost ({len(notes)}) | — |")
    L += [""] + [f"({i}) {n}" for i, n in enumerate(notes, 1)]
    L += ["", f"**Live MTTD:** {h['live_mttd']}. Includes ~3–7 s of bridge lag (pcaps are tailed from a shared disk).", "",
          "| Run | Rule (approved by a human admin) | Approval → rule on switch | **MTTC** (approval → victim < 100 pps) | Victim pps before → 15 s after |",
          "|---|---|---:|---:|---|"]
    for c in mttc:
        v = "not reached" if c.get("mttc_s") is None else f"**{c['mttc_s']:.2f} s**"
        L.append(f"| {c['run']} | {c['target']} | {c['approval_to_applied_s']:.2f} s | {v} | "
                 f"{c['victim_pps_before']} → {c['victim_pps_after_15s']} ({c['reduction']:.0%}) |")
    L += ["", "#### Offline lab coverage: DEV (tuned on) vs HELD-OUT (never tuned on), kept separate", "",
          "| Scenario | DEV (runs 2+3) | HELD-OUT (run4) |", "|---|---|---|"]
    for sc in sorted(set(dev) | set(held)):
        L.append(f"| {sc.replace('_', ' ')} | {_cell(dev.get(sc))} | {_cell(held.get(sc))} |")
    L += ["", f"Held-out: **{h['heldout_detected']} attacks detected**, **{h['heldout_false_alarms']} false alarms** "
          "on benign + flash-crowd traffic. Times are offline MTTD after flow export.",
          "† negative: L2 flagged 2-packet victim fragments just before the scenario started (a known false-positive source, not tuned away).", "",
          "#### Agent triage accuracy vs lab ground truth (10 attacks + 2 benign per set)", "",
          "| | Rules | Lightning (LLM) | ML (L2) |", "|---|---:|---:|---:|"]
    for name, t in (("DEV", tdev), ("HELD-OUT", thel)):
        m = t["metrics"]
        L.append(f"| Attack type correct, {name} | {frac(m['rules'], 'attack_type_correct')} | "
                 f"{frac(m['llm'], 'attack_type_correct')} | {frac(m['ml'], 'attack_type_correct')} |")
    for name, t in (("DEV", tdev), ("HELD-OUT", thel)):
        m = t["metrics"]
        L.append(f"| False alarms (benign, flash crowd), {name} | {m['rules']['false_alarm_rate']:.0%} | "
                 f"{m['llm']['false_alarm_rate']:.0%} | {m['ml']['false_alarm_rate']:.0%} |")
    misses = [f"{r['scenario'].replace('_', ' ')} → \"{r['llm']}\"" for r in thel["rows"]
              if r["expected_family"] and not r["llm_type_ok"]]
    L += ["", f"Lightning's held-out misses: {'; '.join(misses)}. **Live, it called the UDP flood a \"SYN flood\" in "
          f"{h['udp_misnamed']} runs**; v6.1.0 found one cause (the incident carried the previous flood's ML label) and fixed it, not yet re-measured live.",
          "", END]
    return "\n".join(L), h


def splice(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise SystemExit("results markers missing")
    a, b = text.index(START), text.index(END) + len(END)
    return text[:a] + block + text[b:]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    block, _ = build()
    bad = []
    for p in TARGETS:
        text = p.read_text(encoding="utf-8").replace("\r\n", "\n")
        new = splice(text, block)
        if args.check:
            if new != text:
                bad.append(p.name)
        else:
            p.open("w", encoding="utf-8", newline="\n").write(new)
    if bad:
        print("results drifted from the results files in: " + ", ".join(bad) + " (run python scripts/readme_results.py)")
        sys.exit(1)
    print("results block " + ("up to date" if args.check else "written"))


if __name__ == "__main__":
    main()
